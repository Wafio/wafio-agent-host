// HostConfig configures RunHost, the host agent: the eBPF firewall, runtime
// tracing, telemetry to the control plane and the local API.
type HostConfig struct {
	ListenAddr string
	// eBPF kernel-level firewall (Linux only)
	EBPFEnabled   bool
	EBPFInterface string
	EBPFXDPObject string
	EBPFTCObject  string
	EBPFPinPath   string
	EBPFXDPMode   string // auto|skb|driver|hw
	// EBPFMapScale sizes the preallocated BPF maps: "auto" or empty sizes
	// them by the host memory, a number above 0 and at most 1 forces the
	// scale (see wafebpf.ComputeMapSizes).
	EBPFMapScale string
	// eBPF runtime security tracing (Linux only)
	TraceEnabled    bool
	TraceObjectPath string
	LSMEnabled      bool // BPF-LSM: outbound connect and addressed send blocking by IP
	LSMBlockConnect bool // LSM: deny socket_connect to blocklisted IPs
	// Protected processes: never targeted by Kill enforcement. Added
	// to the built-in list unless ProtectedReplaceDefaults; see
	// wafebpf.ProtectedProcessConfig and host_protect_config.go.
	ProtectedProcessNames    []string
	ProtectedExePaths        []string
	ProtectedReplaceDefaults bool
	// Server push (agent → wafio server telemetry)
	ServerURL string // e.g. "http://localhost:9087"
	// AgentAPIKey is the key of the retired pre-host model. The control plane
	// no longer accepts it and the agent never sends it; it is read only to
	// log a warning (see warnAgentAPIKey).
	AgentAPIKey string
	// HostKey is the bearer secret generated by the web panel for a single
	// registered Host. It authenticates every agent process running on
	// that host (eBPF + WAF).
	HostKey string
	// AgentName is a stable process identifier scoped to the host. The
	// control plane uses it to keep multiple agent processes on the same
	// host distinguishable. Defaults to `<hostname>@<kind>` when empty.
	AgentName string
	// GeoIP enrichment (MaxMind). When set (and eBPF is active), the agent
	// periodically resolves source IPs seen by the kernel and populates the
	// `wafio_geoip` map so XDP geo-blocking can make per-packet decisions
	// without a kernel-side prefix tree. Empty: WAFIO_GEO_COUNTRY_DB_PATH,
	// then the legacy WAFIO_GEOIP_DB_PATH.
	GeoIPDBPath string

	// gRPC stream (eBPF agent mode).
	// When GRPCServer is set the agent connects to the control plane via
	// mTLS gRPC and streams telemetry instead of (or in addition to) HTTP push.
	GRPCServer     string // host:port of gRPC listener, e.g. "wafio.example.com:9090"
	GRPCServerName string // SNI override (empty = use GRPCServer hostname)
	GRPCClientCert string // path to PEM client cert (e.g. /etc/wafio/agent/client.crt)
	GRPCClientKey  string // path to PEM client key  (e.g. /etc/wafio/agent/client.key)
	GRPCCACert     string // path to PEM CA cert     (e.g. /etc/wafio/agent/ca.crt)

	// Local API token. When the local listener runs
	// (ListenAddr), RunHost generates a random token at start, writes it to
	// LocalAPITokenFile (empty = DefaultLocalAPITokenFile; mode 0600, or 0640
	// with LocalAPITokenGroup) and requires it as a Bearer token on every
	// local route except /healthz. This holds when eBPF or tracing failed to
	// start: the failure is logged and the listener still runs.
	LocalAPITokenFile  string
	LocalAPITokenGroup string
}

// DefaultHostConfig returns the host agent defaults.
func DefaultHostConfig() HostConfig {
	return HostConfig{ListenAddr: "127.0.0.1:18089"}
}

// grpcConfigured reports whether the gRPC stream has all it needs to start:
// the address and the three mTLS files.
func grpcConfigured(cfg HostConfig) bool {
	return cfg.GRPCServer != "" && cfg.GRPCClientCert != "" && cfg.GRPCClientKey != "" && cfg.GRPCCACert != ""
}

// warnAgentAPIKey logs that the retired agent API key is ignored. When it is the
// only credential of the HTTP push, the control plane refuses every batch, so
// the warning says how to fix that. The agent starts either way: the firewall
// and tracing do not need the control plane.
func warnAgentAPIKey(cfg HostConfig) {
	if cfg.AgentAPIKey == "" {
		return
	}
	if cfg.HostKey == "" && cfg.ServerURL != "" && !grpcConfigured(cfg) {
		log.Printf("WARNING: only the retired agent API key is set: the control plane accepts only a host key, so its pushes are refused; " +
			"create one in the dashboard (Hosts, Add host) and set WAFIO_HOST_KEY or --host-key, " +
			"or configure the gRPC stream (--grpc-server and the three mTLS files)")
		return
	}
	log.Printf("WARNING: the agent API key (--agent-api-key, WAFIO_AGENT_API_KEY) is no longer used and is ignored; remove it")
}

// RunHost runs the host agent until ctx ends or the local listener fails. It
// runs no WAF pipeline. A component that cannot start (eBPF firewall, tracing,
// GeoIP) is logged and skipped; the rest keeps running.
func RunHost(ctx context.Context, cfg HostConfig) error {
	warnAgentAPIKey(cfg)

	// The preallocated BPF maps are sized once, from the host memory, before
	// either manager loads its objects.
	var mapSizes wafebpf.MapSizes
	if runtime.GOOS == "linux" && (cfg.EBPFEnabled || cfg.TraceEnabled) {
		cpus, err := cebpf.PossibleCPU()
		if err != nil {
			cpus = runtime.NumCPU()
		}
		if mapSizes, err = wafebpf.ResolveMapSizes(cfg.EBPFMapScale, "/", cpus); err != nil {
			return fmt.Errorf("invalid --ebpf-map-scale %q (or %s): %w", cfg.EBPFMapScale, EnvEBPFMapScale, err)
		}
		if mapSizes.Warning != "" {
			log.Printf("WARN: %s", mapSizes.Warning)
		}
		log.Print(mapSizes.LogLine())
	}

	// ── eBPF kernel-level firewall (Linux only) ──
	var ebpfMgr *wafebpf.Manager
	if cfg.EBPFEnabled && runtime.GOOS == "linux" {
		xdpMode := wafebpf.XDPModeAuto
		switch strings.ToLower(cfg.EBPFXDPMode) {
		case "skb":
			xdpMode = wafebpf.XDPModeSKB
		case "driver":
			xdpMode = wafebpf.XDPModeDriver
		case "hw":
			xdpMode = wafebpf.XDPModeHW
		}
		mgr := wafebpf.NewManager(wafebpf.ManagerConfig{
			Interface:     cfg.EBPFInterface,
			XDPObjectPath: cfg.EBPFXDPObject,
			TCObjectPath:  cfg.EBPFTCObject,
			PinPath:       cfg.EBPFPinPath,
			XDPMode:       xdpMode,
			MapSizes:      mapSizes,
		}, nil)
		if err := mgr.Start(ctx); err != nil {
			log.Printf("eBPF start failed: %v (continuing without kernel firewall)", err)
		} else {
			ebpfMgr = mgr
			defer func() {
				if err := ebpfMgr.Stop(); err != nil {
					log.Printf("eBPF stop error: %v", err)
				}
			}()
			log.Printf("eBPF kernel firewall active on %s", cfg.EBPFInterface)
		}
	} else if cfg.EBPFEnabled && runtime.GOOS != "linux" {
		log.Printf("eBPF requested but not supported on %s", runtime.GOOS)
	}

	// ── GeoIP enricher: MaxMind → eBPF wafio_geoip map (Linux only) ──
	// Runs alongside the kernel dataplane so XDP geo-blocking can make
	// per-packet decisions using country codes resolved in userspace.
	if ebpfMgr != nil {
		if dbPath := hostGeoIPPath(cfg.GeoIPDBPath, os.Getenv); dbPath != "" {
			if lookup, err := geo.NewMaxMindLookup(dbPath); err == nil {
				enricher := NewGeoIPEnricher(ebpfMgr, lookup, 10*time.Second)
				SetEBPFGeoEnricher(enricher)
				go enricher.Run(ctx)
				log.Printf("eBPF GeoIP enricher active (MaxMind db: %s)", dbPath)
			} else {
				log.Printf("eBPF GeoIP enricher disabled: cannot open %s: %v", dbPath, err)
			}
		} else {
			log.Printf("eBPF GeoIP enricher disabled: no MaxMind DB configured (set WAFIO_GEO_COUNTRY_DB_PATH or --geoip-db)")
		}
	}

	// ── eBPF runtime security tracing (Linux only) ──
	var traceMgr *wafebpf.TraceManager
	if cfg.TraceEnabled && runtime.GOOS == "linux" {
		tmgr := wafebpf.NewTraceManager(wafebpf.TraceManagerConfig{
			ObjectPath:      cfg.TraceObjectPath,
			LSMEnabled:      cfg.LSMEnabled,
			LSMBlockConnect: cfg.LSMBlockConnect,

			ProtectedProcessNames:    cfg.ProtectedProcessNames,
			ProtectedExePaths:        cfg.ProtectedExePaths,
			ProtectedReplaceDefaults: cfg.ProtectedReplaceDefaults,

			MapSizes: mapSizes,
		}, nil)
		if err := tmgr.Start(ctx); err != nil {
			log.Printf("trace start failed: %v (continuing without runtime tracing)", err)
		} else {
			traceMgr = tmgr
			defer func() {
				if err := traceMgr.Stop(); err != nil {
					log.Printf("trace stop error: %v", err)
				}
			}()
			log.Printf("eBPF runtime security tracing active (%d probes)", traceMgr.Status().Probes)
		}
	} else if cfg.TraceEnabled && runtime.GOOS != "linux" {
		log.Printf("trace requested but not supported on %s", runtime.GOOS)
	}

	errCh := make(chan error, 1)

	// ── Push client: agent → wafio server (if configured) ──
	// The WAF agent has its own telemetry pipeline (see waf_telemetry.go), so
	// this client only posts host info of the eBPF/runtime-tracing agent.
	var pushClient *PushClient
	grpcStarted := false
	if cfg.ServerURL != "" && cfg.HostKey != "" && (cfg.EBPFEnabled || cfg.TraceEnabled) {
		pushClient = NewPushClient(cfg.ServerURL, cfg.ListenAddr, ebpfMgr, traceMgr)
		pushClient.HostKey = cfg.HostKey
		pushClient.AgentName = cfg.AgentName
		log.Printf("agent push client started → %s", cfg.ServerURL)
	} else if cfg.ServerURL != "" && cfg.HostKey == "" {
		log.Printf("WARNING: server URL configured but no WAFIO_HOST_KEY set; push disabled")
	}

	// ── gRPC stream: agent → wafio server (if configured) ──
	// A configured gRPC stream owns event draining and retained receipts.
	// Legacy HTTP runs only when gRPC could not be configured.
	if grpcConfigured(cfg) {
		SetEBPFManagers(ebpfMgr, traceMgr)
		if pushClient != nil {
			SetEBPFPushClientRef(pushClient)
		}
		agentName := cfg.AgentName
		if agentName == "" {
			agentName = os.Getenv("HOSTNAME")
		}
		if err := EnableEBPFGRPCStream(
			cfg.GRPCServer, cfg.GRPCServerName,
			cfg.GRPCClientCert, cfg.GRPCClientKey, cfg.GRPCCACert,
			agentName, cfg.HostKey,
		); err != nil {
			log.Printf("WARNING: eBPF gRPC stream init failed: %v (falling back to HTTP push)", err)
		} else {
			grpcStarted = true
			StartEBPFGRPCStreamIfConfigured(ctx)
			log.Printf("eBPF gRPC stream started → %s", cfg.GRPCServer)
		}
	} else if cfg.GRPCServer != "" {
		log.Printf("WARNING: grpc-server configured but missing grpc-client-cert, grpc-client-key or grpc-ca-cert; gRPC disabled")
	}
	if pushClient != nil && !grpcStarted {
		go pushClient.Run(ctx)
	}

	// Local API: every route except /healthz needs the
	// per-start token — firewall writes, trace events, the enforcement log.
	localToken, err := localAPITokenFor(cfg)
	if err != nil {
		return err
	}

	var ebpfHTTP *wafebpf.FastHTTPHandler
	if ebpfMgr != nil {
		ebpfHTTP = &wafebpf.FastHTTPHandler{Manager: ebpfMgr, AuthToken: localToken}
	}

	var traceHTTP *wafebpf.TraceFastHTTPHandler
	if traceMgr != nil {
		traceHTTP = &wafebpf.TraceFastHTTPHandler{Trace: traceMgr, AuthToken: localToken}
	}

	// SSE handler for real-time streaming (shares manager references)
	sseHTTP := &wafebpf.SSEHandler{Manager: ebpfMgr, Trace: traceMgr, AuthToken: localToken}

	if servesLocalAPI(cfg) {
		server := &fasthttp.Server{
			Name:                         "wafio-agent",
			Handler:                      withLocalAPIAuth(localToken, agentHandler(ebpfHTTP, traceHTTP, sseHTTP)),
			DisablePreParseMultipartForm: true,
			NoDefaultContentType:         true,
			ReduceMemoryUsage:            true,
			ReadTimeout:                  30 * time.Second,
			WriteTimeout:                 0, // disabled for SSE streaming
			IdleTimeout:                  120 * time.Second,
		}
		listeners, err := buildListeners(cfg)
		if err != nil {
			return err
		}
		for _, entry := range listeners {
			ln := entry.ln
			endpoint := entry.endpoint
			defer func() { _ = ln.Close() }() // shutdown path; nothing left to report
			go func() {
				log.Printf("agent http listening on %s", endpoint)
				if err := server.Serve(ln); err != nil && !errors.Is(err, net.ErrClosed) {
					errCh <- err
				}
			}()
		}
		go func() {
			<-ctx.Done()
			_ = server.Shutdown()
		}()
	} else {
		log.Printf("local API: off (--listen is empty); the control plane is the only control path")
	}

	select {
	case <-ctx.Done():
		return nil
	case err := <-errCh:
		return err
	}
}

// hostGeoIPPath is the MaxMind database path of the host agent: the flag, else
// WAFIO_GEO_COUNTRY_DB_PATH, else the legacy WAFIO_GEOIP_DB_PATH. Empty: none.
func hostGeoIPPath(flagValue string, getenv func(string) string) string {
	for _, v := range []string{flagValue, getenv("WAFIO_GEO_COUNTRY_DB_PATH"), getenv("WAFIO_GEOIP_DB_PATH")} {
		if v = strings.TrimSpace(v); v != "" {
			return v
		}
	}
	return ""
}

// agentHandler serves the host agent's local API: SSE, eBPF trace, eBPF
// firewall and /healthz. The caller wraps it in withLocalAPIAuth.
func agentHandler(ebpfHTTP *wafebpf.FastHTTPHandler, traceHTTP *wafebpf.TraceFastHTTPHandler, sseHTTP *wafebpf.SSEHandler) fasthttp.RequestHandler {
	return func(ctx *fasthttp.RequestCtx) {
		// SSE streaming endpoint (must come first — long-lived connection)
		if sseHTTP != nil && sseHTTP.Handle(ctx) {
			return
		}
		// eBPF trace API routes (must come before ebpf to match longer prefix first)
		if traceHTTP != nil && traceHTTP.Handle(ctx) {
			return
		}
		// eBPF API routes
		if ebpfHTTP != nil && ebpfHTTP.Handle(ctx) {
			return
		}

		switch string(ctx.Path()) {
		case "/healthz":
			ctx.SetStatusCode(fasthttp.StatusOK)
			ctx.SetContentType("application/json")
			ctx.SetBodyString(`{"ok":true}`)
		default:
			ctx.SetStatusCode(fasthttp.StatusNotFound)
		}
	}
}

type httpListener struct {
	ln       net.Listener
	endpoint string
}

// buildListeners returns the listener of the local API (ListenAddr).
func buildListeners(cfg HostConfig) ([]httpListener, error) {
	var out []httpListener
	if addr := strings.TrimSpace(cfg.ListenAddr); addr != "" {
		ln, err := net.Listen("tcp", addr)
		if err != nil {
			return nil, err
		}
		out = append(out, httpListener{ln: ln, endpoint: "http://" + addr})
	}
	return out, nil
}
